"""Compile the reviewed public conversation fixtures for the game's Kahlua VM."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def lua(value):
    if value is None:
        return "nil"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return str(value)
    if isinstance(value, str):
        return json.dumps(value, ensure_ascii=True)
    if isinstance(value, list):
        return "{" + ",".join(lua(v) for v in value) + "}"
    return "{" + ",".join("[" + lua(k) + "]=" + lua(v) for k, v in value.items()) + "}"


data = {}
for name in ("real-talk", "predicted", "locks"):
    path = ROOT / "tests/fixtures/emma-talk-polish" / (name + ".json")
    data[name] = json.loads(path.read_text(encoding="utf-8"))
target = ROOT / "tests/ui/SCEmmaTalkPolishData.lua"
target.write_text("-- SPDX-License-Identifier: MIT\n-- Generated by scripts/Build-EmmaTalkPolishData.py. Edit the JSON fixtures.\n"
                  "SurvivorCompanion.EmmaTalkPolishData=" + lua(data) + "\n", encoding="utf-8")
print(target)
baseline_path = ROOT / "tests/fixtures/emma-talk-polish/baseline.json"
if baseline_path.exists():
    baseline = json.loads(baseline_path.read_text(encoding="utf-8"))
    (ROOT / "tests/ui/SCEmmaTalkPolishBaseline.lua").write_text(
        "-- SPDX-License-Identifier: MIT\n-- Original and checkpoint non-regression floors; edit baseline.json.\n"
        "SurvivorCompanion.EmmaTalkPolishBaseline=" + lua(baseline) + "\n", encoding="utf-8")
